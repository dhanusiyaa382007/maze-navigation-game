/* Maze Navigation Game - Data Structures in C
 * Stack  (array)       : maze generation (DFS backtracker), DFS solver, path rebuild
 * Queue  (linked list) : BFS shortest-path solver
 * 2D grid / bitmasks   : maze representation
 * Usage:  maze ascii <w> <h> <seed>   |   maze export <file.js>
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#ifdef _WIN32
#include <conio.h>
#else
#include <termios.h>
#include <unistd.h>
#endif

static const int DX[4] = {0, 1, 0, -1}, DY[4] = {-1, 0, 1, 0};
static const int BIT[4] = {1, 2, 4, 8}; /* N E S W open-passage bits */

typedef struct { int w, h; unsigned char *cells; } Maze;

/* ---------- Stack (array based) ---------- */
typedef struct { int *d; int top; } Stack;
static void s_init(Stack *s, int cap) { s->d = malloc(cap * sizeof(int)); s->top = -1; }
static void s_push(Stack *s, int v) { s->d[++s->top] = v; }
static int  s_pop(Stack *s) { return s->d[s->top--]; }
static int  s_empty(Stack *s) { return s->top < 0; }

/* ---------- Queue (linked list) ---------- */
typedef struct QNode { int v; struct QNode *next; } QNode;
typedef struct { QNode *head, *tail; } Queue;
static void q_enq(Queue *q, int v) {
    QNode *n = malloc(sizeof(QNode)); n->v = v; n->next = NULL;
    if (q->tail) q->tail->next = n; else q->head = n;
    q->tail = n;
}
static int q_deq(Queue *q) {
    QNode *n = q->head; int v = n->v;
    q->head = n->next; if (!q->head) q->tail = NULL;
    free(n); return v;
}
static int q_empty(Queue *q) { return q->head == NULL; }

/* ---------- Maze generation: DFS with explicit stack ---------- */
static void generate(Maze *m, unsigned seed) {
    int n = m->w * m->h;
    srand(seed);
    memset(m->cells, 0, n);
    char *vis = calloc(n, 1);
    Stack s; s_init(&s, n);
    s_push(&s, 0); vis[0] = 1;
    while (!s_empty(&s)) {
        int cur = s.d[s.top], x = cur % m->w, y = cur / m->w;
        int opt[4], k = 0;
        for (int i = 0; i < 4; i++) {
            int nx = x + DX[i], ny = y + DY[i];
            if (nx >= 0 && ny >= 0 && nx < m->w && ny < m->h && !vis[ny * m->w + nx]) opt[k++] = i;
        }
        if (k) {
            int i = opt[rand() % k];
            int nxt = (y + DY[i]) * m->w + (x + DX[i]);
            m->cells[cur] |= BIT[i];
            m->cells[nxt] |= BIT[(i + 2) % 4];
            vis[nxt] = 1; s_push(&s, nxt);
        } else s_pop(&s); /* backtrack */
    }
    free(vis); free(s.d);
}

/* ---------- BFS (queue): shortest path from start to end ---------- */
static int bfs(const Maze *m, int start, int *path, int *visited) {
    int n = m->w * m->h, vc = 0;
    int *par = malloc(n * sizeof(int));
    for (int i = 0; i < n; i++) par[i] = -2;
    Queue q = {NULL, NULL};
    q_enq(&q, start); par[start] = -1;
    while (!q_empty(&q)) {
        int c = q_deq(&q); vc++;
        if (c == n - 1) break;
        for (int i = 0; i < 4; i++) if (m->cells[c] & BIT[i]) {
            int nxt = (c / m->w + DY[i]) * m->w + (c % m->w + DX[i]);
            if (par[nxt] == -2) { par[nxt] = c; q_enq(&q, nxt); }
        }
    }
    while (!q_empty(&q)) q_deq(&q);
    Stack s; s_init(&s, n);                       /* rebuild path with a stack */
    for (int c = n - 1; c != -1; c = par[c]) s_push(&s, c);
    int len = 0; while (!s_empty(&s)) path[len++] = s_pop(&s);
    free(s.d); free(par); *visited = vc; return len;
}

/* ---------- DFS (stack): count cells explored ---------- */
static int dfs_count(const Maze *m) {
    int n = m->w * m->h, vc = 0;
    char *vis = calloc(n, 1);
    Stack s; s_init(&s, n);
    s_push(&s, 0); vis[0] = 1;
    while (!s_empty(&s)) {
        int c = s_pop(&s); vc++;
        if (c == n - 1) break;
        for (int i = 0; i < 4; i++) if (m->cells[c] & BIT[i]) {
            int nxt = (c / m->w + DY[i]) * m->w + (c % m->w + DX[i]);
            if (!vis[nxt]) { vis[nxt] = 1; s_push(&s, nxt); }
        }
    }
    free(vis); free(s.d); return vc;
}

static void print_ascii(const Maze *m) {
    for (int x = 0; x < m->w; x++) printf("+--");
    printf("+\n");
    for (int y = 0; y < m->h; y++) {
        printf("|");
        for (int x = 0; x < m->w; x++) printf("  %c", (m->cells[y*m->w+x] & 2) ? ' ' : '|');
        printf("\n+");
        for (int x = 0; x < m->w; x++) printf("%s+", (m->cells[y*m->w+x] & 4) ? "  " : "--");
        printf("\n");
    }
}

static void export_levels(const char *file) {
    static const char *names[] = {"Easy", "Medium", "Hard", "Expert", "Master"};
    static const int sizes[] = {8, 12, 16, 22, 30};
    FILE *f = fopen(file, "w");
    if (!f) { perror("fopen"); exit(1); }
    fprintf(f, "// Generated by c/maze.c - do not edit\nconst LEVELS = [\n");
    for (int L = 0; L < 5; L++) {
        Maze m = {sizes[L], sizes[L], NULL};
        int n = m.w * m.h;
        m.cells = malloc(n);
        generate(&m, 100 + L * 7);
        int *path = malloc(n * sizeof(int)), vis;
        int len = bfs(&m, 0, path, &vis);
        fprintf(f, " {name:\"%s\",w:%d,h:%d,bfsVisited:%d,dfsVisited:%d,shortest:%d,\n  cells:[", names[L], m.w, m.h, vis, dfs_count(&m), len - 1);
        for (int i = 0; i < n; i++) fprintf(f, "%d%s", m.cells[i], i < n - 1 ? "," : "");
        fprintf(f, "]}%s\n", L < 4 ? "," : "");
        free(path); free(m.cells);
    }
    fprintf(f, "];\n"); fclose(f);
    printf("Exported 5 levels to %s\n", file);
}

/* ---------- Terminal game ---------- */
static int get_key(void) {
#ifdef _WIN32
    return _getch();
#else
    struct termios old, raw; int c;
    if (!isatty(0)) return getchar();
    tcgetattr(0, &old); raw = old; raw.c_lflag &= ~(ICANON | ECHO);
    tcsetattr(0, TCSANOW, &raw); c = getchar(); tcsetattr(0, TCSANOW, &old);
    return c;
#endif
}
static void clear_screen(void) {
#ifdef _WIN32
    system("cls");
#else
    printf("\033[2J\033[H");
#endif
}
static void draw(const Maze *m, int pos, const char *hint) {
    int n = m->w * m->h;
    for (int x = 0; x < m->w; x++) printf("+--");
    printf("+\n");
    for (int y = 0; y < m->h; y++) {
        printf("|");
        for (int x = 0; x < m->w; x++) {
            int i = y * m->w + x;
            char sym = i == pos ? '@' : i == n - 1 ? 'E' : hint[i] ? '.' : ' ';
            printf("%c %c", sym, (m->cells[i] & 2) ? ' ' : '|');
        }
        printf("\n+");
        for (int x = 0; x < m->w; x++) printf("%s+", (m->cells[y*m->w+x] & 4) ? "  " : "--");
        printf("\n");
    }
}
static void play(int size, unsigned seed) {
    int n = size * size;
    Maze m = {size, size, malloc(n)};
    generate(&m, seed);
    int *path = malloc(n * sizeof(int)), vis;
    int optimal = bfs(&m, 0, path, &vis) - 1;
    char *hint = calloc(n, 1);
    Stack hist; s_init(&hist, 100000);   /* stack of previous positions for Undo */
    int pos = 0, moves = 0; const char *msg = "";
    time_t t0 = time(NULL);
    while (pos != n - 1) {
        clear_screen();
        printf("MAZE GAME  (@ = you, E = exit)   Moves: %d   Optimal: %d   Time: %ds\n", moves, optimal, (int)(time(NULL) - t0));
        draw(&m, pos, hint);
        printf("w/a/s/d = move, u = undo, h = hint, q = quit\n%s\n", msg);
        msg = ""; memset(hint, 0, n);
        int k = get_key(), dir = -1;
        if (k == 'w') dir = 0; else if (k == 'd') dir = 1; else if (k == 's') dir = 2; else if (k == 'a') dir = 3;
        else if (k == 'q' || k == EOF) { printf("Bye!\n"); return; }
        else if (k == 'u') { if (!s_empty(&hist)) { pos = s_pop(&hist); moves++; } else msg = "Nothing to undo."; }
        else if (k == 'h') { int len = bfs(&m, pos, path, &vis); for (int i = 0; i < len; i++) hint[path[i]] = 1; }
        if (dir >= 0) {
            if (m.cells[pos] & BIT[dir]) {
                if (hist.top < 99999) s_push(&hist, pos);
                pos = (pos / size + DY[dir]) * size + (pos % size + DX[dir]); moves++;
            } else msg = "Wall!";
        }
    }
    clear_screen(); draw(&m, pos, hint);
    printf("YOU WIN! Moves: %d (optimal %d), Time: %ds\n", moves, optimal, (int)(time(NULL) - t0));
}

int main(int argc, char **argv) {
    if (argc >= 3 && !strcmp(argv[1], "export")) { export_levels(argv[2]); return 0; }
    if (argc >= 2 && !strcmp(argv[1], "play")) {
        int size = argc >= 3 ? atoi(argv[2]) : 8;
        if (size < 3) size = 3;
        if (size > 40) size = 40;
        play(size, argc >= 4 ? (unsigned)atoi(argv[3]) : (unsigned)time(NULL));
        return 0;
    }
    int w = 10, h = 6; unsigned seed = 1;
    if (argc >= 5 && !strcmp(argv[1], "ascii")) { w = atoi(argv[2]); h = atoi(argv[3]); seed = atoi(argv[4]); }
    Maze m = {w, h, malloc(w * h)};
    generate(&m, seed);
    int *path = malloc(w * h * sizeof(int)), vis;
    int len = bfs(&m, 0, path, &vis);
    print_ascii(&m);
    printf("Shortest path: %d steps | BFS explored %d | DFS explored %d\n", len - 1, vis, dfs_count(&m));
    return 0;
}
